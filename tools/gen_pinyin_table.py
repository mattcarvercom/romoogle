TONE_MAP = str.maketrans({
    "ā": "a", "á": "a", "ǎ": "a", "à": "a",
    "ē": "e", "é": "e", "ě": "e", "è": "e",
    "ī": "i", "í": "i", "ǐ": "i", "ì": "i",
    "ō": "o", "ó": "o", "ǒ": "o", "ò": "o",
    "ū": "u", "ú": "u", "ǔ": "u", "ù": "u",
    "ǖ": "v", "ǘ": "v", "ǚ": "v", "ǜ": "v", "ü": "v",
    "Ā": "a", "Á": "a", "Ǎ": "a", "À": "a",
    "Ē": "e", "É": "e", "Ě": "e", "È": "e",
    "Ī": "i", "Í": "i", "Ǐ": "i", "Ì": "i",
    "Ō": "o", "Ó": "o", "Ǒ": "o", "Ò": "o",
    "Ū": "u", "Ú": "u", "Ǔ": "u", "Ù": "u",
})

LINE_RE = re.compile(r"^U\+([0-9A-Fa-f]+):\s*([^\s#]+)")
MAX_READINGS = 3


def strip_tone(s: str) -> str:
    return s.translate(TONE_MAP).lower()


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit("usage: gen_pinyin_table.py <pinyin-src.txt> [out.tsv]")
    src_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else "pak/scripts/pinyin.tsv"

    rows = {}
    with open(src_path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            m = LINE_RE.match(line)
            if not m:
                continue
            cp = int(m.group(1), 16)
            if not 0x4E00 <= cp <= 0x9FFF:
                continue  # CJK Unified Ideographs only (covers traditional)
            char = chr(cp)
            raw = OVERRIDES[char].split(",") if char in OVERRIDES else m.group(2).split(",")
            readings = []
            for r in raw:
                r = strip_tone(r)
                if re.fullmatch(r"[a-z]+", r) and r not in readings:
                    readings.append(r)
                if len(readings) >= MAX_READINGS:
                    break
            if readings:
                rows[cp] = readings

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Romoogle pinyin table. Generated by tools/gen_pinyin_table.py;\n")
        f.write("# do not edit by hand. Source: mozillazg/pinyin-data (Unihan-derived).\n")
        f.write("# format: <hanzi>TAB<readings>  readings = comma-separated, no tones,\n")
        f.write("# common-first, at most 3 per char. Traditional variants included.\n")
        for cp in sorted(rows):
            f.write("%s\t%s\n" % (chr(cp), ",".join(rows[cp])))

    print("wrote %s: %d chars" % (out_path, len(rows)))


if __name__ == "__main__":
    main()
