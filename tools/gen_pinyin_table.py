#!/usr/bin/env python3
"""Generate pak/scripts/pinyin.tsv from mozillazg/pinyin-data.

Dev-time only; not run on the device. The device consumes the generated
TSV via pak/scripts/index.awk at scan time.

Source data (one line per char: "U+XXXX: reading[,reading...]  # char"):
    https://raw.githubusercontent.com/mozillazg/pinyin-data/master/pinyin.txt

Usage:
    python3 tools/gen_pinyin_table.py <pinyin-src.txt> [out.tsv]

Output format (UTF-8, no BOM, LF line endings):
    <hanzi>TAB<readings>   readings = comma-separated, no tones,
                           common-first, at most 3 per char.
"""

import re
import sys

# Common polyphonic characters pinned to their common readings (no tones).
# Replaces the source entry wholesale so rare readings never enter the table.
